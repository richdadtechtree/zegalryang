def tip_for(n: int) -> str:
    """n = 지금까지 쓴 상소의 수. 날마다 다른 요령이 차례로 나옵니다."""
    return CLAUDE_CODE_TOPICS[n % len(CLAUDE_CODE_TOPICS)]


