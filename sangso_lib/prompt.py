    system = SYSTEM.format(max_chars=max_chars)
    user = USER.format(today=f"{today:%Y년 %m월 %d일} ({weekday}요일)", recent=recent, wiki=wiki,
                       cc_new=cc_new, cc_old=cc_old, ai_history=ai_history, profile=profile,
                       tip=tip_for(nth))
    return system, user
